-- TSK-022: canonical PostgreSQL bootstrap for a fresh database.
-- Execute only against a deliberately selected empty development/test target.
-- Repeating this file on its own initialized schema is safe; it is NOT an
-- upgrade script for an unknown existing database (see the migration plan).
-- No seed accounts, credentials, destructive statements, or external calls.

BEGIN;

CREATE TABLE IF NOT EXISTS public.users (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  email TEXT NOT NULL UNIQUE,
  password TEXT NOT NULL,
  role TEXT NOT NULL DEFAULT 'user',
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE UNIQUE INDEX IF NOT EXISTS users_email_lower_unique_idx
  ON public.users (lower(email));

CREATE TABLE IF NOT EXISTS public.cars (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  -- brand is retained temporarily for legacy admin/booking consumers.
  -- New inventory consumers use make; P4 reconciles write/read contracts.
  brand TEXT,
  make TEXT,
  model TEXT,
  vin VARCHAR(17),
  type TEXT,
  category TEXT,
  year INTEGER,
  price NUMERIC(14, 2) CHECK (price IS NULL OR price >= 0),
  mileage INTEGER CHECK (mileage IS NULL OR mileage >= 0),
  color TEXT,
  condition TEXT,
  -- Legacy optimized-search filters; unknown values stay NULL, never guessed.
  transmission TEXT,
  fuel_type TEXT,
  status TEXT NOT NULL DEFAULT 'available',
  -- Financing reads is_available; status remains the authoritative source.
  is_available BOOLEAN GENERATED ALWAYS AS (lower(status) = 'available') STORED,
  image_url TEXT,
  description TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT cars_vin_format CHECK (vin IS NULL OR vin ~ '^[A-HJ-NPR-Z0-9]{17}$')
);

CREATE UNIQUE INDEX IF NOT EXISTS cars_vin_unique_idx
  ON public.cars (vin) WHERE vin IS NOT NULL;
CREATE INDEX IF NOT EXISTS cars_status_idx ON public.cars (status);
CREATE INDEX IF NOT EXISTS cars_make_model_idx ON public.cars (make, model);
CREATE INDEX IF NOT EXISTS idx_cars_make ON public.cars (make);
CREATE INDEX IF NOT EXISTS idx_cars_model ON public.cars (model);
CREATE INDEX IF NOT EXISTS idx_cars_price ON public.cars (price);
CREATE INDEX IF NOT EXISTS cars_created_at_index ON public.cars (created_at DESC);
CREATE INDEX IF NOT EXISTS cars_year_idx ON public.cars (year);

-- Durable spotlight state; one current alert per vehicle, not an in-memory list.
CREATE TABLE IF NOT EXISTS public.vehicle_spotlights (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  car_id INTEGER NOT NULL UNIQUE REFERENCES public.cars(id) ON DELETE CASCADE,
  score INTEGER NOT NULL CHECK (score BETWEEN 0 AND 100),
  tier TEXT NOT NULL CHECK (tier IN ('Bronze','Silver','Gold','Platinum')),
  reason TEXT NOT NULL,
  is_read BOOLEAN NOT NULL DEFAULT FALSE,
  tagged_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS vehicle_spotlights_score_idx ON public.vehicle_spotlights (score DESC, car_id);
CREATE INDEX IF NOT EXISTS vehicle_spotlights_unread_idx ON public.vehicle_spotlights (tagged_at DESC) WHERE NOT is_read;

CREATE TABLE IF NOT EXISTS public.car_specs (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  car_id INTEGER NOT NULL UNIQUE REFERENCES public.cars(id) ON DELETE CASCADE,
  power TEXT,
  engine TEXT,
  drive TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS public.car_images (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  car_id INTEGER NOT NULL REFERENCES public.cars(id) ON DELETE CASCADE,
  image_url TEXT NOT NULL,
  image_type TEXT NOT NULL DEFAULT 'general',
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS car_images_car_id_idx ON public.car_images (car_id);

CREATE TABLE IF NOT EXISTS public.bookings (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  car_id INTEGER NOT NULL REFERENCES public.cars(id) ON DELETE CASCADE,
  booking_date DATE NOT NULL,
  -- The published API uses ranges such as "09:00-10:00", not a SQL TIME.
  time_slot TEXT NOT NULL,
  notes TEXT,
  status TEXT NOT NULL DEFAULT 'pending',
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Preserve the existing active-slot reservation rule; cancelled/completed
-- bookings do not prevent other bookings for the same slot.
CREATE UNIQUE INDEX IF NOT EXISTS uniq_booking
  ON public.bookings (car_id, booking_date, time_slot)
  WHERE status NOT IN ('cancelled', 'completed');
CREATE INDEX IF NOT EXISTS bookings_user_id_idx ON public.bookings (user_id);
CREATE INDEX IF NOT EXISTS bookings_car_date_index ON public.bookings (car_id, booking_date);
CREATE INDEX IF NOT EXISTS bookings_status_index ON public.bookings (status);
CREATE INDEX IF NOT EXISTS bookings_date_status_idx ON public.bookings (booking_date, status);

-- Canonical fresh-install form of the three existing financing migrations.
CREATE TABLE IF NOT EXISTS public.financing_leads (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  reference_code VARCHAR(40) NOT NULL UNIQUE,
  idempotency_key VARCHAR(128) NOT NULL UNIQUE,
  car_id INTEGER NOT NULL REFERENCES public.cars(id) ON DELETE RESTRICT,
  user_id INTEGER REFERENCES public.users(id) ON DELETE SET NULL,
  customer_name VARCHAR(160) NOT NULL,
  customer_phone VARCHAR(40) NOT NULL,
  customer_whatsapp VARCHAR(40),
  customer_email VARCHAR(254),
  vehicle_price_snapshot NUMERIC(14, 2) NOT NULL CHECK (vehicle_price_snapshot > 0),
  down_payment NUMERIC(14, 2) NOT NULL CHECK (down_payment >= 0),
  loan_amount NUMERIC(14, 2) NOT NULL CHECK (loan_amount > 0),
  annual_interest_rate NUMERIC(6, 3) NOT NULL CHECK (annual_interest_rate BETWEEN 0 AND 100),
  loan_term_months INTEGER NOT NULL CHECK (loan_term_months BETWEEN 1 AND 120),
  monthly_payment NUMERIC(14, 2) NOT NULL CHECK (monthly_payment > 0),
  total_payment NUMERIC(14, 2) NOT NULL CHECK (total_payment > 0),
  total_interest NUMERIC(14, 2) NOT NULL CHECK (total_interest >= 0),
  currency VARCHAR(3) NOT NULL DEFAULT 'UGX',
  status VARCHAR(16) NOT NULL DEFAULT 'NEW'
    CHECK (status IN ('NEW', 'CONTACTED', 'QUALIFIED', 'CONVERTED', 'CLOSED')),
  contact_consent BOOLEAN NOT NULL CHECK (contact_consent = TRUE),
  consented_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  last_contacted_at TIMESTAMPTZ,
  converted_at TIMESTAMPTZ,
  admin_notes TEXT NOT NULL DEFAULT '' CHECK (char_length(admin_notes) <= 4000),
  deleted_at TIMESTAMPTZ,
  deleted_by INTEGER REFERENCES public.users(id) ON DELETE SET NULL,
  deletion_reason TEXT
);

CREATE INDEX IF NOT EXISTS financing_leads_status_created_idx
  ON public.financing_leads (status, created_at DESC);
CREATE INDEX IF NOT EXISTS financing_leads_active_status_created_idx
  ON public.financing_leads (status, created_at DESC) WHERE deleted_at IS NULL;
CREATE INDEX IF NOT EXISTS financing_leads_car_id_idx ON public.financing_leads (car_id);
CREATE INDEX IF NOT EXISTS financing_leads_user_id_idx ON public.financing_leads (user_id);

-- PostgreSQL form of the upstream exchange repository's schema. observed_at
-- is nullable for historical snapshots; Sprint 16 supplies it for new rates.
CREATE TABLE IF NOT EXISTS public.exchange_rate_snapshots (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  base_currency CHAR(3) NOT NULL,
  rates JSONB NOT NULL CHECK (jsonb_typeof(rates) = 'object'),
  provider VARCHAR(80) NOT NULL,
  retrieved_at TIMESTAMPTZ NOT NULL,
  observed_at TIMESTAMPTZ,
  expires_at TIMESTAMPTZ NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT exchange_rate_expiry_after_retrieval CHECK (expires_at > retrieved_at)
);

CREATE INDEX IF NOT EXISTS exchange_rate_latest_snapshot
  ON public.exchange_rate_snapshots (base_currency, retrieved_at DESC, id DESC);
CREATE INDEX IF NOT EXISTS exchange_rate_expiry_lookup
  ON public.exchange_rate_snapshots (base_currency, expires_at DESC);

COMMIT;
